/* =============================================================================
   SmartPark — standalone build
   Inlines css/styles.css and js/*.js into one portable file:
       node build-standalone.js
   Result: standalone.html — a single file you can double-click (or carry on a
   USB stick) for a live demo: no server, no install, works offline.
   index.html + css/ + js/ stay the source of truth; re-run this after edits.
============================================================================= */
const fs = require("fs");
const path = require("path");

const root = __dirname;
const read = f => fs.readFileSync(path.join(root, f), "utf8");

function inline(htmlText, file, needle, wrapper) {
  if (htmlText.indexOf(needle) === -1) throw new Error("Marker not found in index.html: " + needle);
  const code = read(file).trim();
  if (code.indexOf("</scr" + "ipt>") !== -1) throw new Error(file + " contains a literal closing script tag");
  return htmlText.replace(needle, wrapper[0] + "\n" + code + "\n" + wrapper[1]);
}

let out = read("index.html");

out = inline(out, "css/styles.css", '<link rel="stylesheet" href="css/styles.css" />', ["<style>", "</style>"]);
// order matters: db.js defines window.SP, app.js the shell, admin.js the console
["js/db.js", "js/app.js", "js/admin.js"].forEach(function (f) {
  out = inline(out, f, '<script src="' + f + '"></script>', ["<script>", "</script>"]);
});
out = out.replace("<title>SmartPark", "<!-- Generated by build-standalone.js — edit index.html, css/ or js/ instead. -->\n  <title>SmartPark");

fs.writeFileSync(path.join(root, "standalone.html"), out);
console.log("standalone.html written (" + (Buffer.byteLength(out) / 1024).toFixed(1) + " KB) — open it directly in a browser.");
